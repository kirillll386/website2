function renderCards(items, containerId, type) {
    const container = document.getElementById(containerId);
    if (!container) return;
    
    if (items.length === 0) {
        container.innerHTML = '<p style="text-align: center; color: #666; grid-column: 1/-1;">Информация будет добавлена</p>';
        return;
    }
    
    container.innerHTML = items.map(item => `
        <div class="card">
            <div class="card__image">
                ${item.image ? `<img src="${item.image}" alt="${item.name}" onerror="this.parentElement.innerHTML='Фото не добавлено'">` : 'Фото не добавлено'}
            </div>
            <div class="card__content">
                <h3 class="card__title">${item.name}</h3>
                <span class="card__type ${type === 'bike' ? 'card__type--bike' : 'card__type--moto'}">${item.type || (type === 'bike' ? 'Велосипед' : 'Мотоцикл')}</span>
                ${item.description ? `<p class="card__description">${item.description}</p>` : ''}
                ${item.specs && Object.keys(item.specs).length > 0 ? `
                    <ul class="card__specs">
                        ${Object.entries(item.specs).map(([key, value]) => 
                            `<li class="card__spec"><strong>${key}:</strong> ${value}</li>`
                        ).join('')}
                    </ul>
                ` : ''}
                ${item.price ? `<p style="margin-top: 1rem; font-weight: 600; color: #e74c3c; font-size: 1.1rem;">${item.price}</p>` : ''}
            </div>
        </div>
    `).join('');
}

document.addEventListener('DOMContentLoaded', () => {
    renderCards(bikes, 'bikes-list', 'bike');
    renderCards(motos, 'motos-list', 'moto');
});
